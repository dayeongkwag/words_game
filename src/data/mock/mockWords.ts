/** 플래그 문자열을 불리언 필드로 변환한다. */
function flagsOf(raw: string | undefined) {
  const f = raw ?? '';
  return {
    isProperNoun: f.includes('P'),
    isNeologism: f.includes('N'),
    isTrendWord: f.includes('T'),
    isSlang: f.includes('S'),
    isBrand: f.includes('B'),
  };
}

/**
 * Row 튜플을 WordEntry 로 변환한다.
 * 실제 approved_words.json 과 완전히 같은 형태를 만들어,
 * DB 교체 시 게임 코드가 달라지지 않도록 한다.
 */
export const MOCK_WORDS: WordEntry[] = ROWS.map((row, index) => {
  const [word, category, subcategory, difficulty, definition, flags] = row;
  const normalizedWord = normalizeWord(word);
  return {
    id: `wd-${String(index + 1).padStart(6, '0')}`,
    word,
    normalizedWord,
    length: toSyllables(normalizedWord).length,
    category,
    subcategory,
    difficulty,
    definition,
    ...flagsOf(flags),
    puzzleSuitable: true,
    status: 'approved' as const,
  };
});
